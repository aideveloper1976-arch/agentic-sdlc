#!/usr/bin/env node
// Boots every built MCP server over stdio, performs the MCP handshake and calls tools/list.
// Fails if any server does not start or exposes no tools.
//   node scripts/mcp-smoke.mjs              # smoke test (used in CI)
//   node scripts/mcp-smoke.mjs --catalog    # also regenerate docs/tool-catalog.md
import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const serversDir = path.join(root, "mcp-servers");
const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "mcp-smoke-"));

// Placeholder values so servers that validate config at startup can boot. No network calls are made.
const env = {
  ...process.env,
  GITHUB_TOKEN: "smoke-test", GITHUB_OWNER: "example", GITHUB_REPO: "example",
  ATLASSIAN_BASE_URL: "https://example.atlassian.net", ATLASSIAN_EMAIL: "smoke@example.com", ATLASSIAN_API_TOKEN: "smoke-test",
  JIRA_ENABLED: "false", CONFLUENCE_ENABLED: "false",
};
// Point every working/evidence directory into the temp dir so a smoke run never writes into the repo.
for (const key of ["EVIDENCE_DIR", "EVIDENCE_PATH", "ALERTS_DIR", "REPORTS_DIR", "SCREENSHOT_DIR", "DOM_SNAPSHOT_DIR", "UAT_EVIDENCE_DIR",
  "UX_DIR", "VISUAL_DIR", "DOWNLOAD_DIR", "DOCUMENT_INTAKE_ROOT", "DOCUMENT_EVIDENCE_DIR", "DOCUMENT_REQUIREMENTS_DIR",
  "DOCUMENT_RESEARCH_DIR", "TRACEABILITY_REPORT_DIR", "PROJECT_ROOT", "CODE_EXECUTION_ALLOWED_DIR"]) {
  env[key] = path.join(tmp, key.toLowerCase());
}
env.TRACEABILITY_DB_PATH = path.join(tmp, "traceability.db");

function listTools(entry) {
  return new Promise((resolve, reject) => {
    const child = spawn(process.execPath, [entry], { stdio: ["pipe", "pipe", "ignore"], env, cwd: tmp });
    let buf = "";
    const timer = setTimeout(() => { child.kill(); reject(new Error("timed out after 20s")); }, 20000);
    const send = (m) => child.stdin.write(JSON.stringify(m) + "\n");
    child.on("exit", (code) => { clearTimeout(timer); reject(new Error(`exited early with code ${code}`)); });
    child.stdout.on("data", (d) => {
      buf += d;
      const lines = buf.split("\n");
      buf = lines.pop();
      for (const line of lines) {
        let msg; try { msg = JSON.parse(line); } catch { continue; }
        if (msg.id === 1) {
          send({ jsonrpc: "2.0", method: "notifications/initialized" });
          send({ jsonrpc: "2.0", id: 2, method: "tools/list" });
        } else if (msg.id === 2) {
          clearTimeout(timer);
          child.removeAllListeners("exit");
          child.kill();
          resolve({ server: msg.result?.serverInfo, tools: msg.result?.tools ?? [] });
        }
      }
    });
    send({ jsonrpc: "2.0", id: 1, method: "initialize", params: { protocolVersion: "2024-11-05", capabilities: {}, clientInfo: { name: "mcp-smoke", version: "1.0.0" } } });
  });
}

const results = [];
let failed = 0;
for (const name of fs.readdirSync(serversDir).sort().filter((d) => fs.existsSync(path.join(serversDir, d, "package.json")))) {
  const pkg = JSON.parse(fs.readFileSync(path.join(serversDir, name, "package.json"), "utf8"));
  const entry = path.join(serversDir, name, pkg.main || "dist/index.js");
  try {
    const { tools } = await listTools(entry);
    if (tools.length === 0) throw new Error("no tools exposed");
    results.push({ name, description: pkg.description || "", tools });
    console.log(`ok   ${name.padEnd(24)} ${String(tools.length).padStart(3)} tools`);
  } catch (err) {
    failed++;
    console.log(`FAIL ${name.padEnd(24)} ${err.message}`);
  }
}
const total = results.reduce((n, r) => n + r.tools.length, 0);
console.log(`\n${results.length} servers started, ${total} tools listed, ${failed} failed`);

if (process.argv.includes("--catalog")) {
  const oneLine = (s = "") => s.replace(/\s+/g, " ").replace(/\|/g, "\\|").trim();
  const out = [
    "# Tool catalogue",
    "",
    "<!-- Generated by `node scripts/mcp-smoke.mjs --catalog`. Do not edit by hand. -->",
    "",
    `${results.length} servers, ${total} tools. Each list below is what the server returns from \`tools/list\`.`,
    "",
  ];
  for (const r of results) {
    out.push(`## ${r.name}`, "", `${r.tools.length} tools · [source](../mcp-servers/${r.name})`, "", "| Tool | Description |", "|---|---|");
    for (const t of r.tools) out.push(`| \`${t.name}\` | ${oneLine(t.description)} |`);
    out.push("");
  }
  fs.writeFileSync(path.join(root, "docs", "tool-catalog.md"), out.join("\n"));
  console.log("wrote docs/tool-catalog.md");
}
process.exit(failed ? 1 : 0);
